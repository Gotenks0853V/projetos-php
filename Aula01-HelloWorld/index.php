<?php

    // Definição de variável em PHP começa com cifrão ($)
    $primeiroNome = "José";
    $segundoNome = "Bezerra";

    // Concatenação simples de strings, feita com aspas duplas
    echo "Hello World! $primeiroNome $segundoNome";

    // Concatenação utilizando ponto(.) para juntar variáveis
    echo '<br> Hello World! '.$primeiroNome.' '.$segundoNome;
?>
